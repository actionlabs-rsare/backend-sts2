-- Unit S2 (Transfer & Approval) core schema: transactions, lines, holdings, approvals (OI-16).
-- Forward-only, backward-compatible (practices.md). Prefix: transactions_.
-- NOTE (CR-S2-01/03): Flyway reads classpath:db/migration only, so this unit migration lives here
-- rather than db/migrations/transactions/. Version is date-namespaced to avoid collisions with
-- S1/S3 in parallel; the integrator owns cross-unit migration ordering (see unit audit change request).

-- Human-readable transfer reference (TRF-000001): 3-letter prefix + sequence (Gate 2 deviation).
CREATE SEQUENCE IF NOT EXISTS transactions_ref_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE transactions_transaction (
    id               VARCHAR(20)  PRIMARY KEY,
    type             VARCHAR(20)  NOT NULL,
    transfer_type    VARCHAR(20)  NOT NULL,
    status           VARCHAR(30)  NOT NULL,
    company_code     VARCHAR(20)  NOT NULL,
    transaction_date DATE         NOT NULL,
    srf_no           VARCHAR(40),
    remarks          VARCHAR(500),
    is_exception     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP    NOT NULL,
    posted_at        TIMESTAMP
);
CREATE INDEX idx_txn_company ON transactions_transaction (company_code);
CREATE INDEX idx_txn_status ON transactions_transaction (status);
CREATE INDEX idx_txn_date ON transactions_transaction (transaction_date);

CREATE TABLE transactions_transaction_line (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id            VARCHAR(20) NOT NULL REFERENCES transactions_transaction (id),
    line_no                   INTEGER     NOT NULL,
    from_stockholder_code     VARCHAR(40) NOT NULL,
    to_stockholder_code       VARCHAR(40) NOT NULL,
    share_class_id            VARCHAR(60) NOT NULL,
    shares                    BIGINT      NOT NULL,
    source_certificate_number VARCHAR(60) NOT NULL
);
CREATE INDEX idx_txn_line_txn ON transactions_transaction_line (transaction_id);

-- Current shareholding per (stockholder, company, share class) — the posting outcome (TR-012).
CREATE TABLE transactions_holding (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stockholder_code VARCHAR(40) NOT NULL,
    company_code     VARCHAR(20) NOT NULL,
    share_class_id   VARCHAR(60) NOT NULL,
    shares           BIGINT      NOT NULL,
    CONSTRAINT uq_holding_owner UNIQUE (stockholder_code, company_code, share_class_id)
);

CREATE TABLE transactions_approval_request (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(20)  NOT NULL REFERENCES transactions_transaction (id),
    level          INTEGER      NOT NULL,
    required_role  VARCHAR(30)  NOT NULL,
    decision       VARCHAR(20)  NOT NULL,
    actor          VARCHAR(100),
    reason         VARCHAR(500),
    created_at     TIMESTAMP    NOT NULL,
    decided_at     TIMESTAMP
);
CREATE INDEX idx_approval_txn ON transactions_approval_request (transaction_id);

