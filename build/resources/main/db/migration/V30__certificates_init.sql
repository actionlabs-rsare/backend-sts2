-- Unit S3 — Certificate & Numbering (SL-002, TR-017, TR-018, TR-004).
-- Owner: Team S3. Forward-only; never edit once merged (tasks.md construction rules).
-- Loaded from classpath:db/migration/certificates/ (see CR-S3-01 for the build wiring).
--
-- Numbering design — GAPLESS (S3-Q7: "needs to be incremental and no gap"):
--   * One counter row per (share class, origin) in number_sequence.next_value. Origin =
--     original | replacement, so replacement numbers come from a SEPARATE series (TR-004).
--   * The counter moves ONLY through the SECURITY DEFINER functions below, inside the caller's
--     transaction: the UPDATE holds the row lock until commit, and a rolled-back print gives its
--     number back. (PostgreSQL SEQUENCE objects are not transactional and would leave gaps.)
--   * Target DB-role model: the app role gets EXECUTE on these functions and no UPDATE on
--     number_sequence.next_value, so it cannot rewind or jump the counter (security-nfr T3).
--   * A trigger allows the counter only to stay or move +1 once the series has issued a number,
--     and freezes the starting point from then on (a moved start would skip or reuse numbers).
--   * UNIQUE (share_class_id, certificate_number) is the last line of defence against reuse.
--   * Certificates are never deleted (Gate 3 Q4 / OI-19); their identity is immutable.
--   * The 10 printed fields (user-ticked real certificate, 2026-09-29) are saved on the certificate
--     at print time so a reprint shows exactly what was signed.

CREATE TABLE number_sequence (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    share_class_id  VARCHAR(64)  NOT NULL,
    origin          VARCHAR(20)  NOT NULL CHECK (origin IN ('original', 'replacement')),
    start_number    BIGINT       NOT NULL DEFAULT 1 CHECK (start_number >= 1),
    next_value      BIGINT       NOT NULL DEFAULT 1 CHECK (next_value >= 1),
    numbering_mode  VARCHAR(20)  NOT NULL DEFAULT 'Automatic' CHECK (numbering_mode IN ('Automatic', 'Manual')),
    updated_at      TIMESTAMPTZ  NOT NULL,
    updated_by      VARCHAR(100) NOT NULL,
    CONSTRAINT uq_number_sequence_class_origin UNIQUE (share_class_id, origin),
    CONSTRAINT ck_number_sequence_not_behind_start CHECK (next_value >= start_number)
);

CREATE TABLE certificate (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certificate_number       VARCHAR(20)   NOT NULL,
    share_class_id           VARCHAR(64)   NOT NULL,
    company_code             VARCHAR(20)   NOT NULL,
    holder_stockholder_code  VARCHAR(40)   NOT NULL,
    shares                   BIGINT        NOT NULL CHECK (shares > 0),
    status                   VARCHAR(20)   NOT NULL CHECK (status IN ('Issued', 'Replaced', 'Cancelled', 'Transferred', 'Voided', 'Posted')),
    indicator                VARCHAR(20)   NOT NULL DEFAULT '' CHECK (indicator IN ('', 'Replacement', 'Treasury')),
    origin                   VARCHAR(20)   NOT NULL CHECK (origin IN ('original', 'replacement')),
    transaction_id           VARCHAR(40)   NOT NULL,
    line_no                  INTEGER       NOT NULL CHECK (line_no >= 1),
    print_mode               VARCHAR(20)   NOT NULL CHECK (print_mode IN ('PrePrintedForm', 'SystemTemplate')),
    manually_assigned        BOOLEAN       NOT NULL DEFAULT FALSE,
    approved_by              VARCHAR(100),
    -- The printed face (10 ticked fields; number + shares above; words/day/month/year derived).
    issued_on                DATE          NOT NULL,
    stock_type               VARCHAR(100)  NOT NULL,
    company_name             VARCHAR(200)  NOT NULL,
    holder_name              VARCHAR(200)  NOT NULL, -- always a company (S3-Q9); still never logged
    par_value                NUMERIC(19,4) NOT NULL CHECK (par_value >= 0),
    president_name           VARCHAR(200)  NOT NULL,
    corporate_secretary_name VARCHAR(200)  NOT NULL,
    printed_at               TIMESTAMPTZ   NOT NULL,
    printed_by               VARCHAR(100)  NOT NULL,
    version                  INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT uq_certificate_class_number UNIQUE (share_class_id, certificate_number),
    CONSTRAINT uq_certificate_transaction_line UNIQUE (transaction_id, line_no),
    CONSTRAINT ck_certificate_manual_approved CHECK (NOT manually_assigned OR approved_by IS NOT NULL)
);

CREATE INDEX idx_certificate_transaction ON certificate (transaction_id);
CREATE INDEX idx_certificate_holder ON certificate (holder_stockholder_code);

-- ---------------------------------------------------------------------------
-- Counter functions (SECURITY DEFINER, fixed search_path).
-- ---------------------------------------------------------------------------

-- The next value the counter WILL hand out; read-only (safe in read-only transactions).
CREATE OR REPLACE FUNCTION certificates_peek_next(p_share_class_id TEXT, p_origin TEXT)
RETURNS BIGINT
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path FROM CURRENT
AS $$
    SELECT COALESCE(
        (SELECT next_value FROM number_sequence WHERE share_class_id = p_share_class_id AND origin = p_origin),
        1)
$$;

-- Takes the next number and advances the counter by exactly one. The row lock is held until the
-- caller's transaction ends; a rollback returns the number (gapless).
CREATE OR REPLACE FUNCTION certificates_next_number(p_share_class_id TEXT, p_origin TEXT)
RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER
SET search_path FROM CURRENT
AS $$
DECLARE
    v_taken BIGINT;
BEGIN
    UPDATE number_sequence
       SET next_value = next_value + 1
     WHERE share_class_id = p_share_class_id AND origin = p_origin
    RETURNING next_value - 1 INTO v_taken;
    IF v_taken IS NULL THEN
        RAISE EXCEPTION 'no numbering configured for % / %', p_share_class_id, p_origin
            USING ERRCODE = 'no_data_found';
    END IF;
    RETURN v_taken;
END
$$;

-- Sets the starting point (SL-002). Allowed only while the series has issued nothing, so numbers
-- stay gapless and are never reused. Returns the new next value.
CREATE OR REPLACE FUNCTION certificates_set_start(p_share_class_id TEXT, p_origin TEXT, p_start BIGINT)
RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER
SET search_path FROM CURRENT
AS $$
DECLARE
    v_start BIGINT;
    v_next  BIGINT;
BEGIN
    IF p_start IS NULL OR p_start < 1 THEN
        RAISE EXCEPTION 'starting point must be >= 1' USING ERRCODE = 'check_violation';
    END IF;
    SELECT start_number, next_value INTO v_start, v_next
      FROM number_sequence
     WHERE share_class_id = p_share_class_id AND origin = p_origin
       FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'no numbering configured for % / %', p_share_class_id, p_origin
            USING ERRCODE = 'no_data_found';
    END IF;
    IF v_next > v_start THEN
        RAISE EXCEPTION 'starting point is locked: series % / % has already issued numbers (gapless)',
            p_share_class_id, p_origin USING ERRCODE = 'check_violation';
    END IF;
    UPDATE number_sequence
       SET start_number = p_start, next_value = p_start
     WHERE share_class_id = p_share_class_id AND origin = p_origin;
    RETURN p_start;
END
$$;

-- ---------------------------------------------------------------------------
-- Integrity triggers: gapless counter, no deletion, immutable identity (S3-Q7, OI-19, TR-004, T5).
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION certificates_guard_counter()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.share_class_id IS DISTINCT FROM OLD.share_class_id OR NEW.origin IS DISTINCT FROM OLD.origin THEN
        RAISE EXCEPTION 'a numbering series cannot change its share class or origin'
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF OLD.next_value > OLD.start_number THEN
        -- The series has issued numbers: start frozen, counter stays or moves +1 only.
        IF NEW.start_number <> OLD.start_number THEN
            RAISE EXCEPTION 'starting point is locked once a certificate has been issued (gapless)'
                USING ERRCODE = 'check_violation';
        END IF;
        IF NEW.next_value <> OLD.next_value AND NEW.next_value <> OLD.next_value + 1 THEN
            RAISE EXCEPTION 'certificate numbers must stay gapless (counter % -> %)', OLD.next_value, NEW.next_value
                USING ERRCODE = 'check_violation';
        END IF;
    ELSIF NOT (NEW.next_value = NEW.start_number
               OR (NEW.next_value = OLD.next_value + 1 AND NEW.start_number = OLD.start_number)) THEN
        -- Nothing issued yet: either (re)set the start (next = start) or take the first number.
        RAISE EXCEPTION 'certificate numbers must stay gapless (start %, counter %)', NEW.start_number, NEW.next_value
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_number_sequence_gapless
    BEFORE UPDATE ON number_sequence
    FOR EACH ROW EXECUTE FUNCTION certificates_guard_counter();

CREATE OR REPLACE FUNCTION certificates_forbid_delete()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'certificates and numbering series are never deleted; change the status instead (OI-19)'
        USING ERRCODE = 'restrict_violation';
END
$$;

CREATE TRIGGER trg_certificate_no_delete
    BEFORE DELETE ON certificate
    FOR EACH ROW EXECUTE FUNCTION certificates_forbid_delete();

CREATE TRIGGER trg_number_sequence_no_delete
    BEFORE DELETE ON number_sequence
    FOR EACH ROW EXECUTE FUNCTION certificates_forbid_delete();

CREATE OR REPLACE FUNCTION certificates_freeze_identity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.certificate_number IS DISTINCT FROM OLD.certificate_number
       OR NEW.share_class_id IS DISTINCT FROM OLD.share_class_id
       OR NEW.origin IS DISTINCT FROM OLD.origin
       OR NEW.transaction_id IS DISTINCT FROM OLD.transaction_id
       OR NEW.issued_on IS DISTINCT FROM OLD.issued_on
       OR NEW.holder_name IS DISTINCT FROM OLD.holder_name
       OR NEW.shares IS DISTINCT FROM OLD.shares THEN
        RAISE EXCEPTION 'a printed certificate''s number, class, holder, shares and date are immutable (TR-004)'
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_certificate_freeze_identity
    BEFORE UPDATE ON certificate
    FOR EACH ROW EXECUTE FUNCTION certificates_freeze_identity();
